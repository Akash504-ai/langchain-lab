from dotenv import load_dotenv

load_dotenv()

import os

from langchain_groq import ChatGroq
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser


# ==========================================
# 1. MODEL CONFIGURATION
# ==========================================

MODEL = os.getenv("MODEL")

if not MODEL:
    raise ValueError(
        "MODEL is not set. Add MODEL to your .env file."
    )

llm = ChatGroq(
    model=MODEL,
    temperature=0.7,
    max_tokens=4000
)

parser = StrOutputParser()


# ==========================================
# 2. HUMAN WRITING STYLE
# ==========================================

HUMAN_STYLE = """
Write naturally, like a real human writer.

Follow these rules:
- Use clear, simple, and natural language.
- Avoid robotic or repetitive sentences.
- Avoid unnecessary jargon and complicated vocabulary.
- Vary sentence length to make the writing flow naturally.
- Use active voice whenever appropriate.
- Explain technical concepts with relatable examples.
- Use transitions that connect ideas smoothly.
- Avoid generic introductions and repetitive conclusions.
- Do not invent statistics, research findings, or quotations.
- Keep the writing engaging and useful to the reader.
- Avoid unnecessarily formal or exaggerated language.
- Do not mention that the content was generated by AI.
"""


# ==========================================
# 3. OUTLINE GENERATION PROMPT
# ==========================================

OUTLINE_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are an experienced blog strategist and content planner.

        Your task is to create a detailed, logical outline
        for a blog post based on the user's requirements.

        Follow the selected writing style:
        {human_style}

        Requirements:
        1. Create a compelling and relevant title.
        2. Write an introduction that establishes the topic.
        3. Organize the main content into logical sections.
        4. Include useful subsections where appropriate.
        5. Arrange sections in a natural learning sequence.
        6. Include relevant examples or practical applications.
        7. End with a meaningful conclusion.
        8. Suggest an FAQ section when appropriate.
        9. Avoid repetitive sections.
        10. Match the outline to the requested audience and length.

        Return only the blog outline.
        Do not write the complete blog yet.
        """
    ),
    (
        "human",
        """
        Topic: {topic}

        Tone: {tone}

        Target audience: {audience}

        Desired length: {word_count} words

        Additional instructions: {instructions}
        """
    )
])


# ==========================================
# 4. BLOG DRAFT GENERATION PROMPT
# ==========================================

DRAFT_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are a professional blog writer.

        Write a complete first draft using the supplied outline.

        Follow the selected writing style:
        {human_style}

        Writing requirements:
        1. Follow the outline's structure.
        2. Write an engaging introduction.
        3. Explain each section clearly and thoroughly.
        4. Use examples to make difficult concepts easier.
        5. Keep paragraphs readable and well organized.
        6. Use Markdown headings and subheadings.
        7. Use bullet points or numbered lists when useful.
        8. Maintain the requested tone throughout.
        9. Write for the specified target audience.
        10. Aim for the requested word count.
        11. Avoid repeating the same information.
        12. Do not invent facts, statistics, or citations.
        13. End with a relevant conclusion.

        Return the complete blog draft in Markdown.

        Do not explain your writing process.
        """
    ),
    (
        "human",
        """
        Blog topic: {topic}

        Tone: {tone}

        Target audience: {audience}

        Desired length: {word_count} words

        Additional instructions: {instructions}

        Approved outline:
        {outline}

        Write the complete blog draft using this outline.
        """
    )
])


# ==========================================
# 5. BLOG POLISHING PROMPT
# ==========================================

POLISH_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are an expert editor and content polisher.

        Your task is to improve the supplied blog draft
        while preserving its original meaning and intent.

        Follow the selected writing style:
        {human_style}

        Editing requirements:
        1. Correct grammar, spelling, and punctuation.
        2. Improve clarity and readability.
        3. Remove unnecessary repetition.
        4. Improve sentence structure and transitions.
        5. Strengthen weak headings where appropriate.
        6. Preserve useful examples and explanations.
        7. Maintain the requested tone and audience level.
        8. Keep the Markdown formatting clean.
        9. Preserve the author's intended meaning.
        10. Do not introduce unsupported facts.
        11. Do not add fabricated citations or references.
        12. Keep the article close to the requested length.

        Return only the final polished blog post in Markdown.
        Do not include editorial notes or explain your changes.
        """
    ),
    (
        "human",
        """
        Original topic: {topic}

        Tone: {tone}

        Target audience: {audience}

        Desired length: {word_count} words

        Additional instructions: {instructions}

        Blog draft:
        {draft}

        Polish this draft and return the final blog post.
        """
    )
])


# ==========================================
# 6. CREATE LANGCHAIN CHAINS
# ==========================================

outline_chain = OUTLINE_PROMPT | llm | parser

draft_chain = DRAFT_PROMPT | llm | parser

final_chain = POLISH_PROMPT | llm | parser


# ==========================================
# 7. BLOG GENERATION FUNCTION
# ==========================================

def generate_blog(
    topic: str,
    tone: str = "Conversational",
    audience: str = "General readers",
    word_count: int = 1000,
    instructions: str = "None"
):
    """
    Generate a blog post through three stages:
    outline -> draft -> polished final blog.
    """

    if not topic.strip():
        raise ValueError("Topic cannot be empty.")

    if word_count < 100 or word_count > 5000:
        raise ValueError(
            "Word count must be between 100 and 5000."
        )

    common_inputs = {
        "topic": topic,
        "tone": tone,
        "audience": audience,
        "word_count": word_count,
        "instructions": instructions,
        "human_style": HUMAN_STYLE
    }

    # Stage 1: Generate the outline
    print("\nGenerating blog outline...\n")

    outline = outline_chain.invoke(common_inputs)

    # Stage 2: Generate the first draft
    print("Writing the first draft...\n")

    draft_inputs = {
        **common_inputs,
        "outline": outline
    }

    draft = draft_chain.invoke(draft_inputs)

    # Stage 3: Polish the draft
    print("Polishing the final blog...\n")

    final_inputs = {
        **common_inputs,
        "draft": draft
    }

    final_blog = final_chain.invoke(final_inputs)

    return {
        "outline": outline,
        "draft": draft,
        "final_blog": final_blog
    }


# ==========================================
# 8. RUN THE APPLICATION
# ==========================================

if __name__ == "__main__":

    print("=" * 50)
    print("       AI BLOG WRITER / GENERATOR")
    print("=" * 50)

    topic = input("\nEnter your blog topic: ").strip()

    tone = input(
        "Choose a tone (Conversational, Professional, "
        "Educational, Casual, Persuasive): "
    ).strip() or "Conversational"

    audience = input(
        "Enter the target audience: "
    ).strip() or "General readers"

    word_count_input = input(
        "Desired word count (default 1000): "
    ).strip()

    word_count = int(word_count_input) if word_count_input else 1000

    instructions = input(
        "Additional instructions (optional): "
    ).strip() or "None"

    try:
        result = generate_blog(
            topic=topic,
            tone=tone,
            audience=audience,
            word_count=word_count,
            instructions=instructions
        )

        print("\n" + "=" * 50)
        print("BLOG OUTLINE")
        print("=" * 50)
        print(result["outline"])

        print("\n" + "=" * 50)
        print("FINAL POLISHED BLOG")
        print("=" * 50)
        print(result["final_blog"])

        # Save the final blog to a Markdown file.
        with open(
            "generated_blog.md",
            "w",
            encoding="utf-8"
        ) as file:
            file.write(result["final_blog"])

        print("\nBlog saved to generated_blog.md")

    except ValueError as error:
        print(f"\nInput error: {error}")

    except Exception as error:
        print(f"\nBlog generation failed: {error}")
